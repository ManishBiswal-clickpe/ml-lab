from pathlib import Path
import matplotlib

matplotlib.use("Agg")
Path("figures").mkdir(exist_ok=True)


import numpy as np
import matplotlib.pyplot as plt
import pandas as pd

dataset = pd.read_csv("Social_Network_Ads.csv")
X = dataset.iloc[:, [2, 3]].values
y = dataset.iloc[:, 4].values
print(X)
print(y)

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.25, random_state=0
)


from sklearn.neighbors import KNeighborsClassifier

classifier = KNeighborsClassifier(n_neighbors=11, metric="minkowski", p=2)
classifier.fit(X_train, y_train)

y_pred = classifier.predict(X_test)
print(y_pred)

print(y_test)

from sklearn.metrics import confusion_matrix

cm = confusion_matrix(y_test, y_pred)


print(cm)

Error = y_pred - y_test
OA = (cm[0, 0] + cm[1, 1]) / len(y_test) * 100
print("OA :", OA, "%")

from matplotlib.colors import ListedColormap

X_set, y_set = X_train, y_train
X1, X2 = np.meshgrid(
    np.linspace(X_set[:, 0].min() - 1, X_set[:, 0].max() + 1, 250),
    np.linspace(X_set[:, 1].min() - 1, X_set[:, 1].max() + 1, 250),
)
plt.contourf(
    X1,
    X2,
    classifier.predict(np.array([X1.ravel(), X2.ravel()]).T).reshape(X1.shape),
    alpha=0.75,
    cmap=ListedColormap(("red", "green")),
)
plt.xlim(X1.min(), X1.max())
plt.ylim(X2.min(), X2.max())
for i, j in enumerate(np.unique(y_set)):
    plt.scatter(
        X_set[y_set == j, 0],
        X_set[y_set == j, 1],
        color=ListedColormap(("red", "green"))(i),
        label=j,
    )
plt.title("K-NN (Training set)")
plt.xlabel("Age")
plt.ylabel("Estimated Salary")
plt.legend()
plt.tight_layout()
plt.savefig("figures/training.png", dpi=150)
plt.close()

