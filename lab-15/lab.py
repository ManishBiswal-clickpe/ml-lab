from pathlib import Path
import matplotlib

matplotlib.use("Agg")
Path("figures").mkdir(exist_ok=True)

import matplotlib.pyplot as plt
import pandas as pd

dataset = pd.read_csv("Liss_III.csv")
X = dataset.iloc[:, [2, 3]].values
y_test = dataset.iloc[:, 5].values
print(X)

from sklearn.cluster import KMeans

kmeans = KMeans(n_clusters=2, init="k-means++", random_state=42)
y_pred = kmeans.fit_predict(X)
y_kmeans = y_pred
y_pred = y_pred + 1

plt.scatter(X[y_kmeans == 0, 0], X[y_kmeans == 0, 1], s=100, c="red", label="Cluster 1")
plt.scatter(
    X[y_kmeans == 1, 0], X[y_kmeans == 1, 1], s=100, c="blue", label="Cluster 2"
)
plt.scatter(
    kmeans.cluster_centers_[:, 0],
    kmeans.cluster_centers_[:, 1],
    s=300,
    c="purple",
    label="Centroids",
)
plt.title("K-Means clustering")
plt.xlabel("Band_2")
plt.ylabel("Band_3")
plt.legend()
plt.savefig("figures/kmeans_clusters.png", dpi=150, bbox_inches="tight")
plt.close()

print(y_pred)

from sklearn.metrics import confusion_matrix

cm = confusion_matrix(y_test, y_pred)
print(cm)
OA = (cm[0, 0] + cm[1, 1]) / len(y_test) * 100
print("OA :", OA, "%")
print(len(y_kmeans))

